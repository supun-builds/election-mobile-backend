const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const forge = require('node-forge');

let cachedPrivateKey = null;

/**
 * Loads and caches the RSA-3072 PKCS#8 private key using the configured passphrase.
 */
function getPrivateKey() {
  if (cachedPrivateKey) return cachedPrivateKey;

  const keyPath = process.env.RESULTS_PRIVATE_KEY_PATH || path.join(__dirname, '../keys/results_private_key.pem');
  const passphrase = process.env.RESULTS_KEY_PASSPHRASE;

  if (!fs.existsSync(keyPath)) {
    throw new Error(`Private key file not found at: ${keyPath}`);
  }

  const pemContent = fs.readFileSync(keyPath, 'utf8');

  try {
    cachedPrivateKey = crypto.createPrivateKey({
      key: pemContent,
      format: 'pem',
      passphrase: passphrase || undefined,
    });
    return cachedPrivateKey;
  } catch (err) {
    if (err.message.includes('bad decrypt') || err.code === 'ERR_OSSL_BAD_DECRYPT') {
      throw new Error('Incorrect passphrase for results_private_key.pem. Please check RESULTS_KEY_PASSPHRASE in .env');
    }
    throw new Error(`Failed to load RSA private key: ${err.message}`);
  }
}

/**
 * Resets cached private key (e.g., if passphrase or file changes at runtime).
 */
function resetPrivateKeyCache() {
  cachedPrivateKey = null;
}

/**
 * Decrypts an ephemeral AES-256 key using RSA-3072-OAEP with SHA-256.
 * @param {string} encryptedKeyBase64 - Base64 encoded 384-byte encrypted key.
 * @returns {Buffer} 32-byte AES key.
 */
function decryptAesKey(encryptedKeyBase64) {
  const privateKey = getPrivateKey();
  const encryptedKeyBuf = Buffer.from(encryptedKeyBase64, 'base64');

  if (encryptedKeyBuf.length !== 384) {
    throw new Error(`Invalid encrypted AES key length: expected 384 bytes, got ${encryptedKeyBuf.length}`);
  }

  const aesKey = crypto.privateDecrypt(
    {
      key: privateKey,
      padding: crypto.constants.RSA_PKCS1_OAEP_PADDING,
      oaepHash: 'sha256',
    },
    encryptedKeyBuf
  );

  if (aesKey.length !== 32) {
    throw new Error(`Decrypted AES key length invalid: expected 32 bytes, got ${aesKey.length}`);
  }

  return aesKey;
}

/**
/**
 * Constructs the exact Additional Authenticated Data (AAD) generated by Member 2.
 * Python: json.dumps({"ballot_id": ballot_id, "election_id": election_id, "encryption_version": encryption_version}, separators=(',', ':'))
 * @param {object} envelope - Ballot envelope
 * @returns {Buffer} UTF-8 Buffer of canonical JSON
 */
function buildAad(envelope) {
  return Buffer.from(
    JSON.stringify({
      ballot_id: envelope.ballot_id,
      election_id: envelope.election_id,
      encryption_version: envelope.encryption_version,
    }),
    'utf8'
  );
}

/**
 * Decrypts AES-256-GCM ciphertext with authentication tag and AAD verification.
 * Python's cryptography AESGCM.encrypt() concatenates ciphertext + 16-byte tag.
 * @param {Buffer} aesKey - 32-byte AES key.
 * @param {string} nonceBase64 - Base64 encoded 12-byte nonce.
 * @param {string} ciphertextBase64 - Base64 encoded (ciphertext + 16-byte auth tag).
 * @param {object} envelope - Full envelope for AAD construction.
 * @returns {string} Decrypted plaintext string.
 */
function decryptAesGcm(aesKey, nonceBase64, ciphertextBase64, envelope) {
  const nonce = Buffer.from(nonceBase64, 'base64');
  if (nonce.length !== 12) {
    throw new Error(`Invalid AES-GCM nonce length: expected 12 bytes, got ${nonce.length}`);
  }

  const rawCiphertext = Buffer.from(ciphertextBase64, 'base64');
  if (rawCiphertext.length < 16) {
    throw new Error('Ciphertext payload is too short to contain 16-byte authentication tag');
  }

  const authTag = rawCiphertext.subarray(rawCiphertext.length - 16);
  const ciphertext = rawCiphertext.subarray(0, rawCiphertext.length - 16);

  const primaryAad = buildAad(envelope);

  // Fallback AAD candidates if envelope fields differ
  const aadCandidates = [
    primaryAad,
    Buffer.from(`${envelope.election_id}:${envelope.ballot_id}`, 'utf8'),
    Buffer.from(`${envelope.ballot_id}:${envelope.election_id}`, 'utf8'),
    null,
  ];

  let lastError = null;

  for (const aad of aadCandidates) {
    try {
      const decipher = crypto.createDecipheriv('aes-256-gcm', aesKey, nonce);
      if (aad && aad.length > 0) decipher.setAAD(aad);
      decipher.setAuthTag(authTag);

      let plaintext = decipher.update(ciphertext, null, 'utf8');
      plaintext += decipher.final('utf8');
      return plaintext;
    } catch (err) {
      lastError = err;
    }
  }

  throw new Error(`AES-GCM authentication failed (tampering or AAD mismatch): ${lastError?.message}`);
}


/**
 * Validates preferential voting rules per Sri Lankan Presidential Election counting:
 * - 1st preference is mandatory.
 * - 2nd and 3rd preferences are optional.
 * - No candidate ID may appear more than once on the same ballot.
 * @param {object} preferences - { "1": "candA", "2": "candB", "3": "candC" }
 * @returns {object} Validated preferences object.
 */
function validatePreferences(preferences) {
  if (!preferences || typeof preferences !== 'object') {
    throw new Error('Preferences payload must be a JSON object');
  }

  const p1 = preferences['1'] || preferences[1];
  if (!p1 || typeof p1 !== 'string' || !p1.trim()) {
    throw new Error('First preference ("1") is mandatory');
  }

  const chosen = new Set();
  chosen.add(p1.trim());

  const p2 = preferences['2'] || preferences[2];
  if (p2 && typeof p2 === 'string' && p2.trim()) {
    if (chosen.has(p2.trim())) {
      throw new Error(`Duplicate candidate detected in 2nd preference: ${p2}`);
    }
    chosen.add(p2.trim());
  }

  const p3 = preferences['3'] || preferences[3];
  if (p3 && typeof p3 === 'string' && p3.trim()) {
    if (chosen.has(p3.trim())) {
      throw new Error(`Duplicate candidate detected in 3rd preference: ${p3}`);
    }
    chosen.add(p3.trim());
  }

  return {
    '1': p1.trim(),
    ...(p2 ? { '2': p2.trim() } : {}),
    ...(p3 ? { '3': p3.trim() } : {}),
  };
}

/**
 * Decrypts a ballot envelope. Supports both:
 * 1. Version 1: AES-256-GCM + RSA-3072-OAEP-SHA256
 * 2. Version 0: Legacy Fernet token (starts with 'gAAAAA')
 * @param {string|object} raw - Envelope JSON string, object, or Fernet token.
 * @returns {object|null} Decrypted preferences object { "1": "...", "2": "...", "3": "..." } or null.
 */
function decryptBallot(raw) {
  if (!raw) return null;

  // Check for legacy Fernet vote (Version 0)
  if (typeof raw === 'string' && raw.startsWith('gAAAAA')) {
    return decryptLegacyFernet(raw);
  }

  let envelope = raw;
  if (typeof raw === 'string') {
    try {
      envelope = JSON.parse(raw);
    } catch {
      return null;
    }
  }

  if (!envelope || typeof envelope !== 'object') {
    return null;
  }

  // Envelope Header Validation
  const expectedVersion = 1;
  const expectedAlgorithm = 'AES-256-GCM+RSA-3072-OAEP-SHA256';
  const expectedKeyId = process.env.EXPECTED_KEY_ID || 'results-key-v1';

  if (envelope.encryption_version !== expectedVersion) {
    throw new Error(`Unsupported encryption version: ${envelope.encryption_version}`);
  }

  if (envelope.algorithm !== expectedAlgorithm) {
    throw new Error(`Unsupported algorithm: ${envelope.algorithm}`);
  }

  if (envelope.key_id && envelope.key_id !== expectedKeyId) {
    throw new Error(`Key ID mismatch: expected ${expectedKeyId}, got ${envelope.key_id}`);
  }

  if (!envelope.encrypted_key || !envelope.ciphertext || !envelope.nonce) {
    throw new Error('Malformed envelope: missing encrypted_key, ciphertext, or nonce');
  }

  // 1. Decrypt Ephemeral AES-256 Key
  const aesKey = decryptAesKey(envelope.encrypted_key);

  // 2. Decrypt Payload using AES-256-GCM
  const plaintext = decryptAesGcm(
    aesKey,
    envelope.nonce,
    envelope.ciphertext,
    envelope
  );

  // 3. Parse and Validate voter preferences
  const preferencesJson = JSON.parse(plaintext);
  return validatePreferences(preferencesJson);
}

/**
 * Decrypts legacy Fernet tokens (for existing test records in MongoDB).
 */
function decryptLegacyFernet(encryptedText) {
  try {
    const keyBytes = Buffer.from(
      process.env.VOTE_ENCRYPTION_KEY || process.env.FRIEND_ENCRYPTION_KEY || '',
      'base64'
    );
    if (keyBytes.length < 32) return null;

    const encryptionKey = keyBytes.slice(16, 32);
    const tokenBuf = Buffer.from(
      encryptedText.replace(/-/g, '+').replace(/_/g, '/'),
      'base64'
    );

    const iv = tokenBuf.slice(9, 25);
    const ciphertext = tokenBuf.slice(25, tokenBuf.length - 32);

    const decipher = forge.cipher.createDecipher('AES-CBC', forge.util.createBuffer(encryptionKey));
    decipher.start({ iv: forge.util.createBuffer(iv) });
    decipher.update(forge.util.createBuffer(ciphertext));

    if (!decipher.finish()) return null;

    const parsed = JSON.parse(decipher.output.toString());
    return validatePreferences(parsed);
  } catch {
    return null;
  }
}

module.exports = {
  decryptBallot,
  decryptAesKey,
  decryptAesGcm,
  validatePreferences,
  resetPrivateKeyCache,
};
